// 工作时的转轮帧序与祝福语呼吸色阶，颜色取 Claude Code 原生 accent 橙
// 转轮每 150ms 一帧；文字呼吸每 4 帧走一阶，一整圈 8 阶 ≈ 5s
const FRAME_MS = 150
const FRAME_STEPS = 4
const ACCENT = 0x00d97757
const DEFAULT_BG = 0x01000000
const RAMP = ['#6e3b28', '#8f4d35', '#b05f3d', '#d97757', '#e2896a', '#d97757', '#b05f3d', '#8f4d35']
const SPIN_GLYPHS = ['✢', '✶', '✻', '✽']
const packCell = (glyph: string, fg: number) =>
  new Uint8Array(Uint32Array.of(glyph.codePointAt(0)!, fg, DEFAULT_BG).buffer).toBase64()
const SPIN = SPIN_GLYPHS.map(g => packCell(g, ACCENT))

const fmt = (n: number): string =>
  n < 1000 ? String(n) : n < 1_000_000 ? `${+(n / 1000).toFixed(1)}k` : `${+(n / 1_000_000).toFixed(2)}M`

const plural = (n: number, word: string) => `${n} ${word}${n === 1 ? '' : 's'}`

// 缓存命中率色阶：冷缓存刺眼，越热越绿
export const cacheTone = (hit: number): string =>
  hit < 20 ? '#e5484d' : hit < 40 ? '#f76b15' : hit < 60 ? '#ffb224' : hit < 80 ? '#4a9eff' : '#30a46c'

// 换一句不重复的祝福语
const reroll = (x: number | null): number => {
  let n = x ?? 0
  while (n === x) n = Math.floor(Math.random() * BLESSINGS.length)
  return n
}

const looping = new Set<string>()
// 最近一次绘制时是否在工作；由 render 每次绘制刷新，动画循环每 tick 读取
let workingNow = false
export const register: Register = on => {
  on('session.start', async ($, e, next) => {
    const now = await $.clock.now()
    await update($, bless, () => now % BLESSINGS.length)
    // 抬高代次，让热重载后旧模块残留的动画循环自行退出
    await update($, gen, g => g + 1)
    return next(e)
  })

  on('turn.start', async ($, e, next) => {
    await update($, stats, () => EMPTY)
    return next(e)
  })

  // 工具调用计数：deny 或报错记一次失败
  on('tool.call', async ($, e, next) => {
    let ok = false
    try {
      const result = await next(e)
      ok = result.deny === undefined && !result.isError
      return result
    } finally {
      await update($, stats, s => ({ ...s, tools: s.tools + 1, failed: s.failed + (ok ? 0 : 1) }))
    }
  })

  // 一次模型请求一步：请求数、输入输出、缓存命中都在这里累加
  on('turn.step', async function* ($, e, next) {
    const result = yield* next(e)
    const usage = result.usage
    if (usage) {
      try {
        await update($, stats, s => ({
          requests: s.requests + 1,
          in: s.in + usage.input_tokens + usage.cache_read_input_tokens + usage.cache_creation_input_tokens,
          out: s.out + usage.output_tokens,
          cached: s.cached + usage.cache_read_input_tokens,
        }))
      } catch {
        /* 统计是附带的：写失败不能打断模型的回答 */
      }
    }
    return result
  })

  on('turn.complete', async ($, e, next) => {
    // 只统计主循环的轮次，子 agent 的 turn 不更新天气条
    if (!e.agentId) {
      const n = (await read($, turns)) + 1
      await update($, turns, () => n)
      if (n % 3 === 0) await update($, bless, reroll)
    }
    return next(e)
  })

  on('ui.render', { component: 'AbovePrompt' }, async ($, e, next) => {
    if (e.props.hasSurvey) return next(e)

    const { Box, Button, Text } = $.ui.resolve(e)
    const s = await read($, stats)
    const isWorking = e.props.isWorking
    workingNow = isWorking

    // 本次行动的各段按有无依次出现，段间统一 · 分隔；还没开始就一行 idle
    const left: unknown[] = []
    const add = (key: string, node: unknown) => {
      if (left.length) left.push(<Text key={`sep-${key}`} dimColor>{'  ·  '}</Text>)
      left.push(node)
    }
    const hit = s.in ? Math.round((s.cached / s.in) * 100) : 0
    if (s.tools) add('tools', <Text key="tools" dimColor>{plural(s.tools, 'tool')}</Text>)
    if (s.failed) add('failed', <Text key="failed" color="error">{`${s.failed} failed`}</Text>)
    if (s.requests) add('req', <Text key="req" dimColor>{plural(s.requests, 'request')}</Text>)
    if (s.in || s.out)
      add(
        'io',
        <Text key="io">
          <Text color="success">↑ {fmt(s.in)}</Text>
          <Text color="error">{'  '}↓ {fmt(s.out)}</Text>
        </Text>
      )
    if (s.in) add('cache', <Text key="cache" color={cacheTone(hit)}>cache {hit}%</Text>)
    if (!left.length) left.push(<Text key="idle" dimColor>idle</Text>)

    const b = await read($, bless)
    let right: unknown = <Box />
    if (b !== null) {
      const button = <Button key="bless" plain label="↻" onPress={() => update($, bless, reroll)} />
      if (isWorking) {
        const fr = await read($, frame)
        const text = (
          <Text key="line" color={RAMP[Math.floor(fr / FRAME_STEPS) % RAMP.length]}>
            {BLESSINGS[b]}
          </Text>
        )
        let spinner: unknown = null
        if (e.surface === 'terminal') {
          const { Raster } = $.ui.resolve(e)
          spinner = <Raster key="spin" columns={1} rows={1} cells={SPIN[fr % SPIN.length]} />
        }

        if (!looping.has(e.requestId)) {
          looping.add(e.requestId)
          const myGen = await read($, gen)
          void (async () => {
            try {
              while (true) {
                await $.clock.sleep(FRAME_MS)
                if (!workingNow || (await read($, gen)) !== myGen) break
                await update($, frame, n => (n + 1) % (RAMP.length * FRAME_STEPS))
              }
            } catch {
              /* 会话关闭等异常，直接退出 */
            } finally {
              looping.delete(e.requestId)
            }
          })()
        }

        right =
          spinner === null ? (
            <Box flexDirection="row" marginRight={5}>
              {text}
              <Box marginLeft={1}>{button}</Box>
            </Box>
          ) : (
            <Box flexDirection="row" marginRight={5}>
              {spinner}
              <Box marginLeft={1}>{text}</Box>
              <Box marginLeft={1}>{button}</Box>
            </Box>
          )
      } else {
        right = (
          <Box flexDirection="row" marginRight={5}>
            <Text key="line" dimColor>
              {BLESSINGS[b]}
            </Text>
            <Box marginLeft={1}>{button}</Box>
          </Box>
        )
      }
    }

    return (
      <Box width={e.props.bodyColumns} justifyContent="space-between" flexDirection="row">
        <Box flexDirection="row" marginLeft={2}>{left}</Box>
        {right}
      </Box>
    )
  })
}